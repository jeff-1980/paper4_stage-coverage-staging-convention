def a2_decile():
    df = load_df()
    df = df.copy()
    df['decile'] = np.minimum((df['t_norm'] * 10).astype(int), 9) + 1
    df['abs_err'] = (df['y_true'] - df['mu']).abs()
    rows = []
    for fd in FDS:
        sub = df[df['fd'] == fd]
        for dec in range(1, 11):
            d = sub[sub['decile'] == dec]
            if len(d) == 0:
                continue
            rows.append(dict(fd=fd, decile=dec, n=len(d),
                              failure_rate=1 - d['covered_sp'].mean(),
                              exceed_qhat_frac=(d['s_t'] > d['q_hat']).mean(),
                              median_s_t=d['s_t'].median(),
                              median_abs_err=d['abs_err'].median(),
                              median_sigma=d['sigma'].median()))
    out = pd.DataFrame(rows)
    out.to_csv(TABLES / 'A2_decile_v4.csv', index=False)
    print('wrote A2_decile_v4.csv', out.shape)
    return out


def _h_suffix(h):
    return '' if h == H_PRIMARY else f'_h{int(h)}'


def table_h_sensitivity():
    """h-sensitivity table: k=K_FIXED held fixed across h in {5,7,10} (not
    linked to h), one row per (fd, method, h) -- 4 FD x 4 methods x 3 h = 48
    rows. MC-Dropout/Split CP's own interval bounds don't depend on h, but
    the CUSUM stage assignment they're binned into does (stage_cusum_h5/
    _h7(unsuffixed)/_h10 each partition samples differently), so their ECR
    still varies across h. Reintroduced in v3 against the corrected Mondrian
    CP (split) definition (see module docstring)."""
    df = load_df()
    rows = []
    for fd in FDS:
        sub_fd = df[df['fd'] == fd]
        for suffix, method_name in METHODS:
            for h in H_MULTS:
                sfx = _h_suffix(h)
                stage_col = f'stage_cusum{sfx}'
                covered_col = f'covered_{suffix}{sfx}' if suffix in ('mo', 'mf') else f'covered_{suffix}'
                isinf_col = f'is_inf_{suffix}{sfx}' if suffix in ('mo', 'mf') else None
                vals = {}
                for stage in ['early', 'middle', 'late']:
                    s = sub_fd[sub_fd[stage_col] == stage]
                    vals[stage] = ecr_per_engine(s, covered_col, isinf_col)
                w = worst_stage(vals)
                rows.append(dict(fd=fd, method=method_name, h_mult=h, k_mult=K_FIXED,
                                  early=vals['early'], middle=vals['middle'], late=vals['late'],
                                  worst_stage=w, late_is_worst=(w == 'late')))
    out = pd.DataFrame(rows)
    out.to_csv(TABLES / 'table_h_sensitivity_v4.csv', index=False)

    lines = tex_header('table_h_sensitivity') + [
        r'\begin{table}[t]',
        r'\caption{h-sensitivity (v3): CUSUM convention, k=0.7 held fixed across '
        r'h $\in \{5, 7, 10\}$ (not linked to h), finite-only ECR, per-engine, 4 FD '
        r'$\times$ 4 methods $\times$ 3 h values = 48 rows.}',
        r'\label{tab:h-sensitivity-v4}', r'\centering', r'\small',
        r'\begin{tabular}{llcccccc}', r'\toprule',
        r'FD & Method & h & k & Early & Middle & Late & Worst \\', r'\midrule']
    for _, r in out.iterrows():
        lines.append(f'{r["fd"]} & {r["method"]} & {r["h_mult"]:.1f} & {r["k_mult"]:.1f} & '
                      f'{r["early"]:.4f} & {r["middle"]:.4f} & {r["late"]:.4f} & {r["worst_stage"]} \\\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
    (TABLES / 'table_h_sensitivity_v4.tex').write_text('\n'.join(lines) + '\n')
    print('wrote table_h_sensitivity_v4.csv/.tex', out.shape)
    return out


