def load_df():
    if 'df' not in _DF_CACHE:
        _DF_CACHE['df'] = pd.read_csv(DATA / 'per_sample_final_v4.csv', comment='#')
    return _DF_CACHE['df']


def get_md5():
    return (DATA / 'per_sample_final_v4.md5').read_text().strip()


def tex_header(func_name):
    return [f'% Generated by aggregate.py::{func_name}',
            f'% Source: data/per_sample_final_v4.csv, md5={get_md5()}']


def ecr_per_engine(sub, covered_col, isinf_col=None):
    if isinf_col is not None:
        sub = sub[~sub[isinf_col]]
    if len(sub) == 0:
        return np.nan
    return float(sub.groupby(['seed', 'unit'])[covered_col].mean().mean())


def worst_stage(vals):
    valid = {k: v for k, v in vals.items() if not np.isnan(v)}
    return min(valid, key=valid.get) if valid else None


def table_main():
    """Main table, finite-only ECR (Mondrian's headline number), unbounded
    rate as its own column."""
    df = load_df()
    rows = []
    for fd in FDS:
        sub_fd = df[df['fd'] == fd]
        for conv_name, stage_col in CONVENTIONS:
            for suffix, method_name in METHODS:
                covered_col = f'covered_{suffix}'
                isinf_col = f'is_inf_{suffix}' if suffix in ('mo', 'mf') else None
                for stage in ['early', 'middle', 'late']:
                    s = sub_fd[sub_fd[stage_col] == stage]
                    if len(s) == 0:
                        continue
                    ecr = ecr_per_engine(s, covered_col, isinf_col)
                    rate = float(s[isinf_col].mean()) if isinf_col else 0.0
                    n_inf = int(s[isinf_col].sum()) if isinf_col else 0
                    rows.append(dict(fd=fd, convention=conv_name, method=method_name, stage=stage,
                                      ecr_finite_only=ecr, unbounded_rate=rate,
                                      n_inf=n_inf, n_total=len(s)))
    out = pd.DataFrame(rows)
    out.to_csv(TABLES / 'table_main_v4.csv', index=False)

    lines = tex_header('table_main') + [
        r'\begin{table}[t]',
        r'\caption{Main table (v4): 4 staging conventions $\times$ 4 methods $\times$ 3 stages, '
        r'per-engine ECR, h=7 primary. ECR is finite-only for all methods (unbounded intervals '
        r'excluded before the per-engine average -- see table\_mondrian\_unbounded\_v4 for the '
        r'two-convention comparison); unbounded rate given separately.}',
        r'\label{tab:main-v4}', r'\centering', r'\small',
        r'\begin{tabular}{lllccc}', r'\toprule',
        r'FD & Convention & Method & Stage & ECR (finite) & Unbounded rate \\', r'\midrule']
    for _, r in out.iterrows():
        lines.append(f'{r["fd"]} & {r["convention"]} & {r["method"]} & {r["stage"].capitalize()} & '
                      f'{r["ecr_finite_only"]:.4f} & {r["n_inf"]}/{r["n_total"]} ({r["unbounded_rate"]:.4f}) \\\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
    (TABLES / 'table_main_v4.tex').write_text('\n'.join(lines) + '\n')
    print('wrote table_main_v4.csv/.tex', out.shape)
    return out


def mondrian_unbounded_table():
    """Kept: the two-convention (unbounded-as-covered vs finite-only) comparison,
    now its own table rather than folded into table_main."""
    df = load_df()
    rows = []
    for fd in FDS:
        sub_fd = df[df['fd'] == fd]
        for conv_name, stage_col in CONVENTIONS:
            for suffix, method_name in [('mo', 'Mondrian CP (online)'), ('mf', 'Mondrian CP (split)')]:
                covered_col, isinf_col = f'covered_{suffix}', f'is_inf_{suffix}'
                for stage in ['early', 'middle', 'late']:
                    s = sub_fd[sub_fd[stage_col] == stage]
                    if len(s) == 0:
                        continue
                    covered_unb = s[covered_col] | s[isinf_col]
                    ecr_unb = float(covered_unb.groupby([s['seed'], s['unit']]).mean().mean())
                    ecr_fin = ecr_per_engine(s, covered_col, isinf_col)
                    rows.append(dict(fd=fd, convention=conv_name, method=method_name, stage=stage,
                                      ecr_unbounded_as_covered=ecr_unb, ecr_finite_only=ecr_fin,
                                      unbounded_rate=float(s[isinf_col].mean()),
                                      n_inf=int(s[isinf_col].sum()), n_total=len(s)))
    out = pd.DataFrame(rows)
    out.to_csv(TABLES / 'table_mondrian_unbounded_v4.csv', index=False)
    print('wrote table_mondrian_unbounded_v4.csv', out.shape)
    return out


def compute_cohort_instances(df, stage_col):
    """(fd,seed,unit) instances with >=1 window in all 3 stages under stage_col.
    MUST group by fd too: unit ids are NOT globally unique (FD001 and FD003
    both have units 1..100), so a (seed,unit) tuple collides across FDs --
    grouping by (seed,unit) alone silently merges two different physical
    engines' stage sets. (Caught and fixed after the initial v2 pass reported
    221 total instances globally; the correct per-FD total is 455.)"""
    pivot = df.groupby(['fd', 'seed', 'unit'])[stage_col].apply(lambda s: set(pd.unique(s)))
    mask = pivot.apply(lambda s: {'early', 'middle', 'late'}.issubset(s))
    return set(pivot[mask].index)


