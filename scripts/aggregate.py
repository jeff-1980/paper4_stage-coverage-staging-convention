"""
Stage 0-R4 aggregation entry point. Reads ONLY from
data/per_sample_final_v4.csv (built by the v4 build_canonical.py, which adds
ONE fix on top of v3's Mondrian-split fix: Split CP's single pooled
calibration quantile q_hat is now the direct k-th order statistic instead of
an np.quantile approximation that silently shifted the selected index by one
-- the same fix, and the same off-by-one bug, as v3's Mondrian CP (split) fix
-- see build_canonical.py's module docstring. Only q_hat and
lo_sp/hi_sp/width_sp/covered_sp differ from v3; every other column, including
Mondrian CP and stage_cusum, is bit-identical, verified by diff). v1's, v2's,
and v3's tables and per_sample_final*.csv are kept, unmodified, under
tables/v1_superseded/, tables/v2_superseded/, tables/v3_superseded/, and
data/ respectively (see README's "superseded" note) -- this script never
reads or writes any of them.

table_h_sensitivity (k held fixed, h in {5,7,10}, 48 rows) was reintroduced
in v3 (previously only existed in the withdrawn v1 pipeline); it is now
regenerated against the v4 canonical file, picking up the Split CP fix too.

Changes vs v1 aggregate.py (carried over from v2/v3, still apply in v4):
  - table_main: Mondrian ECR reported as finite-only (the single number used
    for "which stage is worst"); unbounded rate is its own column, not mixed
    into the headline number. The two-convention (unbounded-as-covered vs
    finite-only) comparison is kept, but moved to its own table
    (table_mondrian_unbounded_v4) rather than cluttering the main table.
  - table_trainpct_cohort: train-set-percentile convention, restricted to the
    "cohort" of (seed,unit) instances that have at least one window in ALL
    THREE stages (many short-lived eval units never reach the train-set's
    absolute-cycle 'late' threshold at all under the full-availability table
    B_trainpct_final -- this table asks whether the worst-stage finding
    changes once that structural imbalance is controlled for). Reported
    side by side with the full-availability version. The same cohort
    restriction is applied to CUSUM as a confirmatory check (excluding
    instances where CUSUM never triggered) -- reported to confirm findings
    are unchanged, not because a different answer was expected.
  - paired_diff: primary CI is a unique-ENGINE block bootstrap (block = one
    raw C-MAPSS unit id's ENTIRE set of instances across all 5 seeds it
    appears as an eval unit in -- a block is drawn or not drawn as a whole,
    10,000 resamples). The old per-(seed,unit)-instance bootstrap is kept as
    a sensitivity column alongside it, not replaced.
  - table_matched: caption states explicitly that the fixed proportions are
    the EVALUATION set's mean CUSUM(h=7) stage occupancy; reports the max
    absolute |ECR_matched - ECR_cusum| across all (fd,method,stage) cells.
  - trainpct_thresholds_final_v4 (the "bucket geometry" table): gains an
    n_cohort_instances column (per fd,seed) alongside the existing
    p33/p67/frac_eval_shorter_than_train_median columns.
"""
