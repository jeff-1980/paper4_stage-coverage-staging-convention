def one_line_answer(df):
    """Does the reversal survive on identical samples?"""
    sub = df[(df['method'] == 'Split CP') & (df['h_mult'] == 7.0)]
    results = {}
    for convention, stage_col in [('fixed', 'stage_fixed'), ('cusum', 'stage_cusum')]:
        per_fd_worst = {}
        for fd in FDS:
            fd_sub = sub[sub['fd'] == fd]
            stage_ecr = {}
            for stage in ['early', 'middle', 'late']:
                st_sub = fd_sub[fd_sub[stage_col] == stage]
                if len(st_sub) == 0:
                    continue
                ecr, n, n_inf = cell_ecr_excl_inf(st_sub)
                stage_ecr[stage] = ecr
            if stage_ecr:
                per_fd_worst[fd] = min(stage_ecr, key=stage_ecr.get)
        results[convention] = per_fd_worst
    print('\nWorst stage per FD, fixed convention:', results['fixed'])
    print('Worst stage per FD, CUSUM convention:', results['cusum'])
    flips = sum(1 for fd in FDS if results['fixed'].get(fd) != results['cusum'].get(fd))
    answer = (f"On identical held-out samples (same predictions, same intervals), the "
              f"worst-covered stage differs between the fixed-fraction and CUSUM staging "
              f"conventions for {flips}/4 datasets -- the reversal "
              f"{'SURVIVES' if flips >= 3 else ('PARTIALLY SURVIVES' if flips >= 1 else 'DOES NOT SURVIVE')} "
              f"the same-sample correction.")
    print('\nONE-LINE ANSWER:', answer)
    (OUT / 'one_line_answer.txt').write_text(answer + '\n')
    return answer


